// L-FRM-06 fixture: the unit canon, re-typed at a call site.
export function feetToMetres(feet: number): number {
  return feet * 0.3048;
}

export function cftToCubicMetres(cft: number): number {
  return cft * 0.028316846592;
}

export function kilogramsToMetricTonnes(kg: number): number {
  return kg / 1000;
}
